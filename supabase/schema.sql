create table if not exists public.favorites (
  profile_id uuid not null references public.profiles(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (profile_id, product_id)
);

create table if not exists public.conversations (
  id bigint generated by default as identity primary key,
  last_message_preview text not null,
  display_timestamp text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.conversation_participants (
  conversation_id bigint not null references public.conversations(id) on delete cascade,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  primary key (conversation_id, profile_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.conversations(id) on delete cascade,
  sender_profile_id uuid not null references public.profiles(id) on delete cascade,
  body text not null,
  display_timestamp text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.trades (
  id bigint generated by default as identity primary key,
  initiator_profile_id uuid not null references public.profiles(id) on delete cascade,
  recipient_profile_id uuid not null references public.profiles(id) on delete cascade,
  status text not null check (status in ('pending', 'accepted', 'declined')),
  message text not null,
  display_timestamp text not null,
  initiator_cash integer,
  recipient_cash integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.trade_items (
  trade_id bigint not null references public.trades(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  side text not null check (side in ('initiator', 'recipient')),
  primary key (trade_id, product_id, side)
);

