-- Backfill brand_archive_pieces from existing products. Group products by
-- (brand_id, lower(trim(title))) so each unique title becomes one archive
-- piece. The first product image (sort_order, then id) supplies the cover.
with grouped_products as (
  select
    p.brand_id,
    p.brand_slug,
    lower(btrim(p.title)) as normalized_title,
    min(p.id) as first_product_id,
    (array_agg(p.title order by p.id asc))[1] as title,
    (array_agg(p.category order by p.id asc))[1] as category,
    (array_agg(p.color order by p.id asc))[1] as color,
    (array_agg(p.description order by p.id asc))[1] as description,
    (array_agg(p.detail_items order by p.id asc))[1] as detail_items
  from public.products p
  where p.brand_id is not null
  group by p.brand_id, p.brand_slug, normalized_title
)
insert into public.brand_archive_pieces (
  brand_id,
  brand_slug,
  slug,
  title,
  season_kind,
  season_year,
  season_label,
  category,
  color,
  cover_image_url,
  description,
  details
)
select
  gp.brand_id,
  gp.brand_slug,
  regexp_replace(lower(gp.normalized_title), '[^a-z0-9]+', '-', 'g') as slug,
  gp.title,
  'UNKNOWN',
  null,
  'Unknown',
  gp.category,
  gp.color,
  (
    select pi.public_url
    from public.product_images pi
    join public.products p2 on p2.id = pi.product_id
    where lower(btrim(p2.title)) = gp.normalized_title
      and p2.brand_id = gp.brand_id
    order by pi.sort_order asc, p2.id asc
    limit 1
  ),
  coalesce(gp.description, '{}'),
  coalesce(gp.detail_items, '[]'::jsonb)
from grouped_products gp
on conflict (brand_id, slug) do nothing;

