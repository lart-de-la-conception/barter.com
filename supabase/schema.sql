-- The public-read policy above exposes every profile row, so restrict WHICH
-- columns the anonymous (logged-out) role may read. Anonymous clients must not be
-- able to scrape member emails, Stripe payout ids, or raw home coordinates via
-- direct PostgREST. Column-level privileges only take effect once the broad
-- table-level grant is removed, hence revoke-all-then-grant-the-safe-columns.
-- The app's anonymous reads select exactly these columns (PUBLIC_PROFILE_COLUMNS
-- in lib/data/marketplace.ts). Authenticated/service_role reads are unaffected;
-- a member reads their own email/stripe fields as the authenticated role.
