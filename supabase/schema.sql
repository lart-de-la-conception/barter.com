-- Trade status transitions (accept / schedule / complete / cancel) are performed
-- exclusively by the server routes using the service-role client, which enforce
-- who may make each transition and in what order. There is intentionally NO
-- client UPDATE policy: a permissive one would let a participant set
-- status='completed' (or accept their own offer) directly via PostgREST with
-- their JWT, bypassing every API-layer guard. With RLS enabled and no UPDATE
-- policy, direct client updates are denied while the service role still writes.
drop policy if exists "trade participants can update trades" on public.trades;

