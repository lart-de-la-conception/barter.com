create or replace function public.current_profile_id()
returns uuid
language sql
stable
as $$
  select id from public.profiles where auth_user_id = auth.uid() limit 1
$$;

-- Used by RLS policies that need "same conversation" checks. A plain EXISTS
-- against public.conversation_participants from another policy on that table
-- causes infinite recursion (PostgreSQL 42P17).
create or replace function public.current_user_participates_in_conversation(p_conversation_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.conversation_participants cp
    where cp.conversation_id = p_conversation_id
      and cp.profile_id = public.current_profile_id()
  );
$$;

revoke all on function public.current_user_participates_in_conversation(bigint) from public;
grant execute on function public.current_user_participates_in_conversation(bigint) to anon;
grant execute on function public.current_user_participates_in_conversation(bigint) to authenticated;
grant execute on function public.current_user_participates_in_conversation(bigint) to service_role;

drop policy if exists "profiles are public read" on public.profiles;
create policy "profiles are public read"
on public.profiles for select
using (true);

drop policy if exists "profiles owner insert" on public.profiles;
create policy "profiles owner insert"
on public.profiles for insert
with check (auth.role() = 'authenticated' and auth.uid() = auth_user_id);

drop policy if exists "profiles owner update" on public.profiles;
create policy "profiles owner update"
on public.profiles for update
using (
  auth.role() = 'authenticated'
  and (
    auth.uid() = auth_user_id
    or (auth_user_id is null and lower(email) = lower(coalesce(auth.jwt() ->> 'email', '')))
  )
)
with check (auth.role() = 'authenticated' and auth.uid() = auth_user_id);

