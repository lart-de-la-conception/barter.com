  exists (
    select 1
    from public.trades
    where public.trades.id = trade_meetups.trade_id
      and (
        public.trades.initiator_profile_id = public.current_profile_id()
        or public.trades.recipient_profile_id = public.current_profile_id()
      )
  )
);

-- Meetup proposals, agreements and confirmations are written exclusively by the
-- server routes via the service-role client. Those routes enforce the dual
-- confirmation rule (each caller may set only their OWN confirmation column) and
-- the proposed-by / status gating. There is intentionally NO client INSERT or
-- UPDATE policy: a permissive UPDATE policy would let one participant set BOTH
-- initiator_confirmed_at and recipient_confirmed_at directly via PostgREST,
-- defeating dual-confirmation and unilaterally completing the trade; a permissive
-- INSERT policy would let them spoof proposed_by_profile_id. With RLS enabled and
-- no such policy, direct client writes are denied while the service role still writes.
drop policy if exists "trade participants can insert meetups" on public.trade_meetups;
drop policy if exists "trade participants can update meetups" on public.trade_meetups;

