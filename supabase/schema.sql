-- Resync identity after INSERT/upsert with explicit `id` (e.g. seed script); otherwise
-- the next DEFAULT id can collide and raise duplicate key on products_pkey.
create or replace function public.sync_products_id_sequence()
returns bigint
language sql
security definer
set search_path = public
as $$
  select setval(
    pg_get_serial_sequence('public.products', 'id'),
    coalesce((select max(id) from public.products), 0),
    true
  );
$$;

revoke all on function public.sync_products_id_sequence() from public;
grant execute on function public.sync_products_id_sequence() to service_role;

